const fs=require('node:fs');
const path=require('node:path');
const root=__dirname;
const read=(p)=>fs.readFileSync(path.join(root,p),'utf8');
const assets=JSON.parse(read('assets.json'));
const giftImages=JSON.parse(read('gift-assets.json'));
const cards=read('src/cards.js');
const tracking=read('src/tracking.js');
fs.mkdirSync(path.join(root,'dist'),{recursive:true});
fs.mkdirSync(path.join(root,'..','src','generated'),{recursive:true});

let giftHtml='';
for(const name of ['results','success','curator','home','about','sales','gift']){
 let html=read('src/'+name+'.html');
 const selected=name==='success'?{download:assets.download}:assets;
 html=html.replace('<!-- CARDS_SCRIPT -->','<script>window.SOULBOX_ASSETS='+JSON.stringify(selected)+';</script>\n<script>'+cards+'</script>');
 html=html.replace('<!-- TRACKING_SCRIPT -->','<script>'+tracking+'</script>');
 // Only files with a hosted URL are included; the rest show a labelled placeholder.
 const hosted=Object.fromEntries(Object.entries(giftImages).filter(([,url])=>url));
 html=html.replace('<!-- GIFT_IMAGES -->','<script>window.SOULBOX_GIFT_IMAGES='+JSON.stringify(hosted)+';</script>');
 if(name==='gift'){giftHtml=html;continue;}
 fs.writeFileSync(path.join(root,'dist',name+'.html'),html);
 console.log(name,html.length);
}

// Turn a page (style + markup + scripts) into one script the backend serves, plus the
// small Webflow loader that goes in the page's footer code.
function buildApp({html,rootId,name,background,noscript,source}){
 const fonts=(html.match(/<link [^>]*fonts\.googleapis[^>]*>/)||[''])[0].match(/href="([^"]+)"/)[1];
 const css=html.match(/<style>([\s\S]*?)<\/style>/)[1];
 const markup=html.slice(html.indexOf('</style>')+8,html.indexOf('<script>')).replace(/<!--[\s\S]*?-->/g,'').trim();
 const scripts=[...html.matchAll(/<script>([\s\S]*?)<\/script>/g)].map((m)=>m[1]);
 const app=[
  '/* SoulBox '+name+'. Generated by webflow/build.js from '+source+'. Do not edit. */',
  '(function(){',
  ' var root=document.getElementById('+JSON.stringify(rootId)+');',
  ' if(!root){root=document.createElement("div");root.id='+JSON.stringify(rootId)+';document.body.appendChild(root);}',
  ' var link=document.createElement("link");link.rel="stylesheet";link.href='+JSON.stringify(fonts)+';document.head.appendChild(link);',
  ' var style=document.createElement("style");style.textContent='+JSON.stringify(css)+';document.head.appendChild(style);',
  ' root.innerHTML='+JSON.stringify(markup)+';',
  '})();',
  ...scripts.map((s)=>';'+s),
 ].join('\n');
 const file=rootId.replace('soulbox-','')+'-app.js';
 fs.writeFileSync(path.join(root,'..','src','generated',file),'module.exports = '+JSON.stringify(app)+';\n');
 const loader=[
  '<!-- SoulBox '+name+'. The app is served by the backend: edit '+source+' in soulbox-backend-new, not here. -->',
  '<style>html,body{margin:0;min-height:100%;background:'+background+'!important}</style>',
  '<div id="'+rootId+'"></div>',
  '<noscript><p style="color:#f4f2ec;font-family:Georgia,serif;text-align:center;padding:40px 20px">'+noscript+'</p></noscript>',
  '<script src="https://soulbox-backend-new.vercel.app/api/'+file+'" defer></script>',
  '',
 ].join('\n');
 fs.writeFileSync(path.join(root,'dist',rootId.replace('soulbox-','')+'.html'),loader);
 console.log(file,app.length,'| Webflow loader',loader.length);
}

// The Gift Flow (Build Brief Part A).
buildApp({html:giftHtml,rootId:'soulbox-gift',name:'Gift Flow',background:'#8C1C2E',source:'webflow/src/gift.html',noscript:'Please turn on JavaScript to send a Gift Box.'});

// The November quiz (Parts C to M): logic, kept questions, images and results module inlined.
{
 const quizAssets=JSON.parse(read('quiz-assets.json'));
 const images={};
 for(const [group,files] of Object.entries(quizAssets)) if(group[0]!=='_') for(const [file,url] of Object.entries(files)) if(url) images[file]=url;
 // Last round's result images that the brief keeps (pre-House reveal, Houses, gradients).
 for(const [file,url] of Object.entries(assets.display)) if(/^(pre_house_reveal|house_of_|gradient_)/.test(file)) images[file]=url;
 const data={legacy:JSON.parse(read('src/quiz/legacy-questions.json')),images};
 let html=read('src/quiz/quiz.html');
 html=html.replace('<!-- TRACKING_SCRIPT -->','<script>'+tracking+'</script>');
 html=html.replace('<!-- QUIZ_DATA -->',
  '<script>'+fs.readFileSync(path.join(root,'..','src','logic','soulbox-logic.js'),'utf8')+'</script>\n'+
  '<script>window.SOULBOX_QUIZ_DATA='+JSON.stringify(data)+';</script>\n'+
  '<script>'+read('src/quiz/results.js')+'</script>');
 buildApp({html,rootId:'soulbox-quiz',name:'Quiz',background:'#1c255d',source:'webflow/src/quiz/quiz.html',noscript:'Please turn on JavaScript to begin your Soul Reading.'});
}
